const target = path.join(DATA_DIR, "eval-cases.json");
const force = process.argv.includes("--force");
// 与 scripts/seed.mjs 迁移过来的旧用例共用同一个文件：这里只补入缺失的 V2 用例，不覆盖别人的数据
const existing = fs.existsSync(target) ? JSON.parse(fs.readFileSync(target, "utf8")) : [];
const known = new Set(existing.map((item) => item.id));
const missing = cases.filter((item) => !known.has(item.id));
const merged = force ? cases : [...existing, ...missing];
